def is_grace_note(note):
  """Check if a note is a grace note using multiple methods"""
  # Method 1: Check duration.isGrace property
  try:
    if hasattr(note.duration, 'isGrace') and note.duration.isGrace:
      return True
  except:
    pass
  
  # Method 2: Check if duration is zero (common for grace notes)
  try:
    if note.duration.quarterLength == 0.0:
      return True
  except:
    pass
  
  # Method 3: Check for grace container
  try:
    if hasattr(note, 'getGrace') and note.getGrace():
      return True
  except:
    pass
  
  # Method 4: Check duration type
  try:
    if hasattr(note.duration, 'type') and 'grace' in str(note.duration.type).lower():
      return True
  except:
    pass
  
  # Method 5: Check if note is in a grace container
  try:
    for context in note.contextSites():
      if 'Grace' in str(type(context)):
        return True
  except:
    pass
  
  return False


def diagnose_semitone_errors(file1, file2):
  """Detailed analysis of ±1 semitone pitch errors"""
  score1 = music21.converter.parse(file1)
  score2 = music21.converter.parse(file2)
  
  print("=== SEMITONE ERROR ANALYSIS ===")
  
  # Get notes with their musical context
  notes1 = list(score1.flatten().notes)
  notes2 = list(score2.flatten().notes)

  if len(notes1) != len(notes2):
    print(f"⚠️  Note count mismatch: {len(notes1)} vs {len(notes2)}")
    return
  
  semitone_errors = []
  plus_one_errors = []
  minus_one_errors = []
  
  # Analyze each note
  for i, (n1, n2) in enumerate(zip(notes1, notes2)):
    if not (hasattr(n1, 'pitch') and hasattr(n2, 'pitch')):
      continue
      
    diff = n2.pitch.midi - n1.pitch.midi
    
    if diff == 1:
      plus_one_errors.append(i)
      semitone_errors.append({
        'index': i,
        'type': '+1',
        'original': n1,
        'decoded': n2,
        'context': get_note_context(score1, n1),
        'measure': get_measure_number(score1, n1)
      })
    elif diff == -1:
      minus_one_errors.append(i)
      semitone_errors.append({
        'index': i,
        'type': '-1',
        'original': n1,
        'decoded': n2,
        'context': get_note_context(score1, n1),
        'measure': get_measure_number(score1, n1)
      })
  
  print(f"Total semitone errors: {len(semitone_errors)}")
  print(f"  +1 semitone errors: {len(plus_one_errors)}")
  print(f"  -1 semitone errors: {len(minus_one_errors)}")
  
  if not semitone_errors:
    print("✅ No semitone errors found!")
    return
  
  # Pattern analysis
  analyze_semitone_patterns(semitone_errors, score1)
  
  # Show detailed examples
  print(f"\n=== DETAILED EXAMPLES (first 10) ===")
  for error in semitone_errors[:10]:
    show_semitone_error_detail(error)
  
  return semitone_errors


def get_note_context(score, note):
  """Get key signature and accidental context for a note"""
  # Find the key signature at this point
  offset = note.offset
  key_sigs = score.flat.getElementsByClass('KeySignature')
  current_key = None
  
  for ks in key_sigs:
    if ks.offset <= offset:
      current_key = ks
    else:
      break
  
  return {
    'key_signature': str(current_key) if current_key else 'C major',
    'has_accidental': note.pitch.accidental is not None,
    'accidental': str(note.pitch.accidental) if note.pitch.accidental else None,
    'pitch_class': note.pitch.pitchClass,
    'step': note.pitch.step,
    'is_grace_note': is_grace_note(note),
  }


def get_measure_number(score, note):
  try:
    if hasattr(note, 'measureNumber') and note.measureNumber:
      return note.measureNumber
  except:
    pass
  
  try:
    measures = score.parts[0].getElementsByClass('Measure')
    note_offset = note.offset
    
    for i, measure in enumerate(measures):
      measure_start = measure.offset
      measure_end = measure_start + measure.duration.quarterLength
      
      if measure_start <= note_offset < measure_end:
        return measure.number if hasattr(measure, 'number') and measure.number else i + 1
  except:
    pass
  
  try:
    flat_with_measures = score.flat
    measures_in_flat = flat_with_measures.getElementsByClass('Measure')
    
    current_measure = 1
    for element in flat_with_measures:
      if isinstance(element, music21.stream.Measure):
        current_measure = element.number if hasattr(element, 'number') and element.number else current_measure
      elif element is note:
        return current_measure
        
  except:
    pass
  
  try:
    # Assume 4/4 time signature if not found
    time_sigs = score.flat.getElementsByClass('TimeSignature')
    beats_per_measure = 4.0
    if time_sigs:
      ts = time_sigs[0]
      beats_per_measure = float(ts.numerator) * (4.0 / ts.denominator)
    
    estimated_measure = int(note.offset / beats_per_measure) + 1
    return estimated_measure
  except:
    pass
  
  return "Unknown"


def analyze_semitone_patterns(errors, score):
  """Analyze patterns in semitone errors"""
  print(f"\n=== PATTERN ANALYSIS ===")
  
  # 1. Direction bias
  plus_ones = [e for e in errors if e['type'] == '+1']
  minus_ones = [e for e in errors if e['type'] == '-1']
  
  if len(plus_ones) > len(minus_ones) * 3:
    print("🔍 Pattern: Mostly +1 errors → Your decoder adds sharps or removes flats")
  elif len(minus_ones) > len(plus_ones) * 3:
    print("🔍 Pattern: Mostly -1 errors → Your decoder adds flats or removes sharps")
  else:
    print("🔍 Pattern: Mixed +1/-1 errors → Inconsistent accidental handling")
  
  # 2. Accidental correlation
  original_with_acc = [e for e in errors if e['context']['has_accidental']]
  original_without_acc = [e for e in errors if not e['context']['has_accidental']]
  
  print(f"  Errors on notes WITH accidentals: {len(original_with_acc)}/{len(errors)}")
  print(f"  Errors on notes WITHOUT accidentals: {len(original_without_acc)}/{len(errors)}")
  
  if len(original_with_acc) > len(original_without_acc) * 2:
    print("  💡 Most errors are on notes with accidentals → Accidental encoding issue")
  elif len(original_without_acc) > len(original_with_acc) * 2:
    print("  💡 Most errors are on naturals → Key signature context issue")
  
  # 3. Key signature correlation
  key_contexts = {}
  for error in errors:
    key = error['context']['key_signature']
    key_contexts[key] = key_contexts.get(key, 0) + 1
  
  print(f"  Errors by key signature:")
  for key, count in sorted(key_contexts.items(), key=lambda x: x[1], reverse=True):
    print(f"    {key}: {count} errors")
  
  # 4. Pitch class analysis
  pitch_classes = {}
  for error in errors:
    pc = error['context']['step']
    pitch_classes[pc] = pitch_classes.get(pc, 0) + 1
  
  print(f"  Most affected note names:")
  for pc, count in sorted(pitch_classes.items(), key=lambda x: x[1], reverse=True)[:5]:
    print(f"    {pc}: {count} errors")



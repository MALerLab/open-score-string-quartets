def find_missing_notes(file1, file2):
  """Find missing/extra notes, chords, and rests using sequence alignment"""
  score1 = music21.converter.parse(file1)
  score2 = music21.converter.parse(file2)
  
  def extract_elements(score):
    elements = []
    for i, element in enumerate(score.flat.notesAndRests):
      if isinstance(element, music21.note.Rest):
        elem_info = {
          'index': i, 
          'type': 'rest', 
          'signature': f"R{element.duration.quarterLength}",
          'duration': element.duration.quarterLength, 'offset': element.offset,
          'measure': get_measure_number(score, element)
        }
      elif hasattr(element, 'pitch'):  # Single note
        elem_info = {
          'index': i, 
          'type': 'note', 
          'signature': f"N{element.pitch.midi}",
          'pitch_name': element.pitch.nameWithOctave, 
          'offset': element.offset,
          'measure': get_measure_number(score, element)
        }
      elif is_chord(element):  # Chord
        pitches = sorted([p.midi for p in element.pitches])
        elem_info = {
          'index': i, 
          'type': 'chord', 
          'signature': f"C[{','.join(map(str, pitches))}]",
          'pitches': [music21.pitch.Pitch(midi=p).nameWithOctave for p in pitches],
          'offset': element.offset, 
          'measure': get_measure_number(score, element)
        }
      else:
        continue
      elements.append(elem_info)
    return elements
  
  elements1 = extract_elements(score1)
  elements2 = extract_elements(score2)
  
  print(f"=== MISSING ELEMENTS ANALYSIS ===")
  print(f"Elements: {len(elements1)} → {len(elements2)} (diff: {len(elements1) - len(elements2):+d})")
  
  # Count by type
  types1 = {'note': 0, 'chord': 0, 'rest': 0}
  types2 = {'note': 0, 'chord': 0, 'rest': 0}
  for e in elements1: types1[e['type']] += 1
  for e in elements2: types2[e['type']] += 1
  
  print(f"Notes: {types1['note']} → {types2['note']} ({types1['note'] - types2['note']:+d})")
  print(f"Chords: {types1['chord']} → {types2['chord']} ({types1['chord'] - types2['chord']:+d})")
  print(f"Rests: {types1['rest']} → {types2['rest']} ({types1['rest'] - types2['rest']:+d})")
  
  # Sequence alignment
  seq1 = [e['signature'] for e in elements1]
  seq2 = [e['signature'] for e in elements2]
  print([
    (e['signature'], e['measure']) 
    for e in elements1 
    if e['type'] == 'chord'
  ])
  print([
    (e['signature'],e['measure'])
    for e in elements2 
    if e['type'] == 'chord'
  ])
  matcher = SequenceMatcher(None, seq1, seq2)
  
  missing_elements = []
  extra_elements = []
  
  for tag, i1, i2, j1, j2 in matcher.get_opcodes():
    if tag == 'delete':
      print(f"\nMISSING from decoded:")
      for idx in range(i1, i2):
        elem = elements1[idx]
        missing_elements.append(elem)
        if elem['type'] == 'rest':
          print(f"  Rest {elem['duration']}♩ at M{elem['measure']} (offset {elem['offset']:.2f})")
        elif elem['type'] == 'note':
          print(f"  Note {elem['pitch_name']} at M{elem['measure']} (offset {elem['offset']:.2f})")
        elif elem['type'] == 'chord':
          pitches_str = '+'.join(elem['pitches'][:3])
          if len(elem['pitches']) > 3: pitches_str += '...'
          print(f"  Chord [{pitches_str}] at M{elem['measure']} (offset {elem['offset']:.2f})")
    
    elif tag == 'insert':
      print(f"\nEXTRA in decoded:")
      for idx in range(j1, j2):
        elem = elements2[idx]
        extra_elements.append(elem)
        if elem['type'] == 'rest':
          print(f"  Rest {elem['duration']}♩ at M{elem['measure']} (offset {elem['offset']:.2f})")
        elif elem['type'] == 'note':
          print(f"  Note {elem['pitch_name']} at M{elem['measure']} (offset {elem['offset']:.2f})")
        elif elem['type'] == 'chord':
          pitches_str = '+'.join(elem['pitches'][:3])
          if len(elem['pitches']) > 3: pitches_str += '...'
          print(f"  Chord [{pitches_str}] at M{elem['measure']} (offset {elem['offset']:.2f})")
  
  # Summary
  total_issues = len(missing_elements) + len(extra_elements)
  if total_issues <= 4:
    print(f"\n✅ Small difference ({total_issues} elements) - easy to fix!")
    missing_types = [e['type'] for e in missing_elements]
    extra_types = [e['type'] for e in extra_elements]
    if 'rest' in missing_types or 'rest' in extra_types:
      print("🎯 Focus on REST encoding")
    if 'note' in missing_types or 'note' in extra_types:
      print("🎯 Focus on NOTE encoding")
    if 'chord' in missing_types or 'chord' in extra_types:
      print("🎯 Focus on CHORD encoding")
  
  return missing_elements, extra_elements



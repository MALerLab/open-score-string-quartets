def compare_offsets(file1, file2, tolerance=0.001):
  """Comprehensive offset/timing comparison"""
  score1 = music21.converter.parse(file1)
  score2 = music21.converter.parse(file2)
  
  print("=== OFFSET/TIMING ANALYSIS ===")
  
  elements1 = list(score1.flat.notesAndRests)
  elements2 = list(score2.flat.notesAndRests)
  
  musical_elements1 = [e for e in elements1 if hasattr(e, 'pitch') or is_chord(e)]
  musical_elements2 = [e for e in elements2 if hasattr(e, 'pitch') or is_chord(e)]
  
  if len(musical_elements1) != len(musical_elements2):
    print(f"⚠️  Element count mismatch: {len(musical_elements1)} vs {len(musical_elements2)}")
    return
  
  offset_differences = []
  duration_differences = []
  timing_shifts = []
  
  for i, (e1, e2) in enumerate(zip(musical_elements1, musical_elements2)):
    offset_diff = e2.offset - e1.offset
    duration_diff = e2.duration.quarterLength - e1.duration.quarterLength
    measure_number = get_measure_number(score1, e1)
    
    if abs(offset_diff) > tolerance:
      offset_differences.append({
        'index': i,
        'original_offset': float(e1.offset),
        'decoded_offset': float(e2.offset),
        'difference': float(offset_diff),
        'element_type': 'chord' if is_chord(e1) else 'note',
        'pitch_info': get_chord_info(e1)['pitch_names'] if get_chord_info(e1) else None,
        'measure': measure_number,
      })
      timing_shifts.append(offset_diff)
    
    if abs(duration_diff) > tolerance:
      duration_differences.append({
        'index': i,
        'original_duration': e1.duration.quarterLength,
        'decoded_duration': e2.duration.quarterLength,
        'difference': duration_diff,
        'element_type': 'chord' if is_chord(e1) else 'note',
        'measure': measure_number,
      })
  
  print(f"Offset differences (>{tolerance}): {len(offset_differences)}")
  print(f"Duration differences (>{tolerance}): {len(duration_differences)}")
  
  # Analyze timing shift patterns
  if timing_shifts:
    print(f"\n=== TIMING SHIFT ANALYSIS ===")
    avg_shift = sum(timing_shifts) / len(timing_shifts)
    print(f"Average timing shift: {avg_shift:.6f} quarter notes")
    
    # Check for systematic shift
    if abs(avg_shift) > tolerance:
      if avg_shift > 0:
        print(f"  → Systematic delay: decoded notes are {avg_shift:.6f} quarter notes later")
      else:
        print(f"  → Systematic advance: decoded notes are {abs(avg_shift):.6f} quarter notes earlier")
    
    # Check for consistent shifts
    unique_shifts = list(set(round(shift, 6) for shift in timing_shifts))
    if len(unique_shifts) == 1:
      print(f"  → All shifts are identical: {unique_shifts[0]:.6f}")
    elif len(unique_shifts) <= 3:
      print(f"  → Limited shift values: {unique_shifts}")
    else:
      print(f"  → Variable shifts: {len(unique_shifts)} different values")
  
  # Show detailed examples
  print(f"\n=== DETAILED OFFSET DIFFERENCES (first 10) ===")
  for i, diff in enumerate(offset_differences[:10]):
    idx = diff['index']
    print(f"Element {idx} ({diff['element_type']}) in Measure {diff['measure']}:")
    print(f"  Pitches: {diff['pitch_info']}")
    print(f"  Offset: {diff['original_offset']:.6f} → {diff['decoded_offset']:.6f}")
    print(f"  Difference: {diff['difference']:+.6f} quarter notes")
    
    # Convert to musical terms
    if abs(diff['difference']) >= 1.0:
      beats = abs(diff['difference'])
      print(f"  = {beats:.2f} beats {'later' if diff['difference'] > 0 else 'earlier'}")
    elif abs(diff['difference']) >= 0.5:
      print(f"  = ~half beat {'later' if diff['difference'] > 0 else 'earlier'}")
    elif abs(diff['difference']) >= 0.25:
      print(f"  = ~quarter beat {'later' if diff['difference'] > 0 else 'earlier'}")
  
  print(f"\n=== DETAILED DURATION DIFFERENCES (first 10) ===")
  for i, diff in enumerate(duration_differences[:10]):
    idx = diff['index']
    print(f"Element {idx} ({diff['element_type']}) in Measure {diff['measure']}:")
    print(f"  Duration: {diff['original_duration']:.6f} → {diff['decoded_duration']:.6f}")
    print(f"  Difference: {diff['difference']:+.6f} quarter notes")
  
  return offset_differences, duration_differences


def analyze_rhythmic_patterns(file1, file2):
  """Analyze rhythmic pattern preservation"""
  score1 = music21.converter.parse(file1)
  score2 = music21.converter.parse(file2)
  
  print("=== RHYTHMIC PATTERN ANALYSIS ===")
  
  elements1 = [e for e in score1.flat.notesAndRests if hasattr(e, 'duration')]
  elements2 = [e for e in score2.flat.notesAndRests if hasattr(e, 'duration')]
  
  # Extract rhythm patterns
  durations1 = [e.duration.quarterLength for e in elements1]
  durations2 = [e.duration.quarterLength for e in elements2]
  
  # Find common duration values
  unique_durations1 = set(durations1)
  unique_durations2 = set(durations2)
  
  print(f"Original duration types: {len(unique_durations1)}")
  print(f"Decoded duration types: {len(unique_durations2)}")
  
  # Common duration names
  duration_names = {
    4.0: "whole", 2.0: "half", 1.0: "quarter", 0.5: "eighth", 
    0.25: "sixteenth", 0.125: "thirty-second", 1.5: "dotted half",
    0.75: "dotted quarter", 0.375: "dotted eighth", 3.0: "dotted whole"
  }
  
  print(f"\nOriginal durations:")
  for dur in sorted(unique_durations1):
    count = durations1.count(dur)
    name = duration_names.get(dur, f"{dur} quarters")
    print(f"  {name}: {count} times")
  
  print(f"\nDecoded durations:")
  for dur in sorted(unique_durations2):
    count = durations2.count(dur)
    name = duration_names.get(dur, f"{dur} quarters")
    print(f"  {name}: {count} times")
  
  # Check for duration quantization issues
  lost_durations = unique_durations1 - unique_durations2
  gained_durations = unique_durations2 - unique_durations1
  
  if lost_durations:
    print(f"\nLost duration types:")
    for dur in sorted(lost_durations):
      name = duration_names.get(dur, f"{dur} quarters")
      print(f"  {name}")
  
  if gained_durations:
    print(f"\nGained duration types:")
    for dur in sorted(gained_durations):
      name = duration_names.get(dur, f"{dur} quarters")
      print(f"  {name}")



def get_chord_info(element):
  """Get detailed chord information"""
  if is_chord(element):
    return {
      'type': 'chord',
      'pitches': tuple(sorted([p.midi for p in element.pitches])),
      'pitch_names': tuple(sorted([p.name for p in element.pitches])),
      'note_count': len(element.pitches),
      'root': element.root().name if len(element.pitches) > 0 else None,
      'bass': element.bass().name if len(element.pitches) > 0 else None,
      'duration': element.duration.quarterLength,
      'offset': element.offset,
      'is_grace': is_grace_note(element)
    }
  elif hasattr(element, 'pitch'):  # Single note
    return {
      'type': 'note',
      'pitches': (element.pitch.midi,),
      'pitch_names': (element.pitch.name,),
      'note_count': 1,
      'root': element.pitch.name,
      'bass': element.pitch.name,
      'duration': element.duration.quarterLength,
      'offset': element.offset,
      'is_grace': is_grace_note(element)
    }
  else:
    return None


def compare_chord_structures(chord1, chord2):
  """Compare two chord structures and identify differences"""
  info1 = get_chord_info(chord1)
  info2 = get_chord_info(chord2)
  
  if not info1 or not info2:
    return None
  
  differences = []
  
  # Type change (note ↔ chord)
  if info1['type'] != info2['type']:
    differences.append(f"Type change: {info1['type']} → {info2['type']}")
  
  # Note count change
  if info1['note_count'] != info2['note_count']:
    differences.append(f"Note count: {info1['note_count']} → {info2['note_count']}")
  
  # Pitch changes
  pitches1 = set(info1['pitches'])
  pitches2 = set(info2['pitches'])
  
  added_pitches = pitches2 - pitches1
  removed_pitches = pitches1 - pitches2
  
  if added_pitches:
    added_names = [music21.pitch.Pitch(midi=p).name for p in added_pitches]
    differences.append(f"Added pitches: {added_names}")
  
  if removed_pitches:
    removed_names = [music21.pitch.Pitch(midi=p).name for p in removed_pitches]
    differences.append(f"Removed pitches: {removed_names}")
  
  return {
    'identical': len(differences) == 0,
    'differences': differences,
    'info1': info1,
    'info2': info2
  }



def strip_invisible_elements(tree:ET.ElementTree, remove_position_modifications=False) -> ET.ElementTree:
  """
  remove all <El print-object="no"/>
  using etree
  """
  root = tree.getroot()

  for measure in reversed(root.findall('.//measure')):
    for el in reversed(measure.findall('.//note[@print-object="no"]')):
      measure.remove(el)
  
    if remove_position_modifications:
      for el in reversed(measure.findall('.//backup')):
        measure.remove(el)
      for el in reversed(measure.findall('.//forward')):
        measure.remove(el)

  return ET.ElementTree(root)


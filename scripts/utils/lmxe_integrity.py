def get_chord_info(element):
  """Get detailed chord information"""
  if is_chord(element):
    return {
      'type': 'chord',
      'pitches': tuple(sorted([p.midi for p in element.pitches])),
      'pitch_names': tuple(sorted([p.name for p in element.pitches])),
      'note_count': len(element.pitches),
      'root': element.root().name if len(element.pitches) > 0 else None,
      'bass': element.bass().name if len(element.pitches) > 0 else None,
      'duration': element.duration.quarterLength,
      'offset': element.offset,
      'is_grace': is_grace_note(element)
    }
  elif hasattr(element, 'pitch'):  # Single note
    return {
      'type': 'note',
      'pitches': (element.pitch.midi,),
      'pitch_names': (element.pitch.name,),
      'note_count': 1,
      'root': element.pitch.name,
      'bass': element.pitch.name,
      'duration': element.duration.quarterLength,
      'offset': element.offset,
      'is_grace': is_grace_note(element)
    }
  else:
    return None


def compare_chord_structures(chord1, chord2):
  """Compare two chord structures and identify differences"""
  info1 = get_chord_info(chord1)
  info2 = get_chord_info(chord2)
  
  if not info1 or not info2:
    return None
  
  differences = []
  
  # Type change (note ↔ chord)
  if info1['type'] != info2['type']:
    differences.append(f"Type change: {info1['type']} → {info2['type']}")
  
  # Note count change
  if info1['note_count'] != info2['note_count']:
    differences.append(f"Note count: {info1['note_count']} → {info2['note_count']}")
  
  # Pitch changes
  pitches1 = set(info1['pitches'])
  pitches2 = set(info2['pitches'])
  
  added_pitches = pitches2 - pitches1
  removed_pitches = pitches1 - pitches2
  
  if added_pitches:
    added_names = [music21.pitch.Pitch(midi=p).name for p in added_pitches]
    differences.append(f"Added pitches: {added_names}")
  
  if removed_pitches:
    removed_names = [music21.pitch.Pitch(midi=p).name for p in removed_pitches]
    differences.append(f"Removed pitches: {removed_names}")
  
  return {
    'identical': len(differences) == 0,
    'differences': differences,
    'info1': info1,
    'info2': info2
  }


def diagnose_chord_differences(file1, file2):
  """Comprehensive chord difference analysis"""
  score1 = music21.converter.parse(file1)
  score2 = music21.converter.parse(file2)
  
  print("=== CHORD STRUCTURE ANALYSIS ===")
  
  elements1 = list(score1.flat.notesAndRests)
  elements2 = list(score2.flat.notesAndRests)
  
  # Filter to notes and chords only
  musical_elements1 = [e for e in elements1 if hasattr(e, 'pitch') or is_chord(e)]
  musical_elements2 = [e for e in elements2 if hasattr(e, 'pitch') or is_chord(e)]
  
  if len(musical_elements1) != len(musical_elements2):
    print(f"⚠️  Musical element count mismatch: {len(musical_elements1)} vs {len(musical_elements2)}")
    return
  
  # Count chord vs note types
  chords1 = [e for e in musical_elements1 if is_chord(e)]
  notes1 = [e for e in musical_elements1 if hasattr(e, 'pitch') and not is_chord(e)]
  chords2 = [e for e in musical_elements2 if is_chord(e)]
  notes2 = [e for e in musical_elements2 if hasattr(e, 'pitch') and not is_chord(e)]
  
  print(f"Original: {len(chords1)} chords, {len(notes1)} single notes")
  print(f"Decoded:  {len(chords2)} chords, {len(notes2)} single notes")
  
  chord_differences = []
  type_changes = []
  pitch_changes = []
  
  for i, (e1, e2) in enumerate(zip(musical_elements1, musical_elements2)):
    comparison = compare_chord_structures(e1, e2)
    
    if comparison and not comparison['identical']:
      measure1 = get_measure_number(score1, e1)
      measure2 = get_measure_number(score2, e2)
      
      chord_differences.append({
        'index': i,
        'comparison': comparison,
        'measure1': measure1,
        'measure2': measure2
      })

      # Categorize the type of difference
      if any('Type change' in diff for diff in comparison['differences']):
        type_changes.append(i)
      if any('pitches' in diff for diff in comparison['differences']):
        pitch_changes.append(i)
  
  print(f"\nChord structure differences: {len(chord_differences)}")
  print(f"  Type changes (note ↔ chord): {len(type_changes)}")
  print(f"  Pitch content changes: {len(pitch_changes)}")
  
  # Show detailed examples
  print(f"\n=== DETAILED CHORD DIFFERENCES (first 10) ===")
  for i, diff in enumerate(chord_differences[:10]):
    idx = diff['index']
    comp = diff['comparison']
    info1 = comp['info1']
    info2 = comp['info2']
    
    print(f"\nElement {idx} in Measure {diff['measure1']}:")
    print(f"  Original: {info1['type']} - {info1['pitch_names']} ({info1['note_count']} notes)")
    print(f"  Decoded:  {info2['type']} - {info2['pitch_names']} ({info2['note_count']} notes)")
    print(f"  Changes: {'; '.join(comp['differences'])}")
  
  return chord_differences



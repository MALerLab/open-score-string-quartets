  plus_ones = len([e for e in errors if e['type'] == '+1'])
  minus_ones = len([e for e in errors if e['type'] == '-1'])
  with_acc = len([e for e in errors if e['context']['has_accidental']])
  without_acc = len([e for e in errors if not e['context']['has_accidental']])
  
  if plus_ones > minus_ones * 2:
    print("🎯 Focus on: Your encoding is losing flats or adding sharps")
